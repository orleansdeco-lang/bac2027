export const ALL_CURRICULUM_SKILLS = CANONICAL_SCIENCES_EXP_SKILLS;

/**
 * Returns all canonical skills for a given subject
 */
export function getCurriculumSkillsForSubject(subjectId: string): (CanonicalSkill & CurriculumSkill)[] {
  return Object.values(CANONICAL_SCIENCES_EXP_SKILLS).filter((s) => s.subjectId === subjectId);
}

/**
 * Returns all canonical skills for a given topic
 */
export function getSkillsForTopic(topicId: string): (CanonicalSkill & CurriculumSkill)[] {
  return Object.values(CANONICAL_SCIENCES_EXP_SKILLS).filter((s) => s.topicId === topicId);
}

/**
 * Returns a canonical skill by its unique identifier
 */
export function getCurriculumSkillById(skillId: string): (CanonicalSkill & CurriculumSkill) | undefined {
  return CANONICAL_SCIENCES_EXP_SKILLS[skillId];
}

