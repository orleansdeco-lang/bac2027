export interface ExamTopicDetails {
  topicNumber: 1 | 2;
  title: string;
  instruction: string;
  exercises: ExamExerciseItem[];
}

export interface ExamFullDetails {
  exam: BacExamItem;
  streamName: string;
  subjectName: string;
  durationLabel: string;
  coefficient: number;
  topic1: ExamTopicDetails;
  topic2: ExamTopicDetails;
  ministryGuidelines: string[];
}

/**
 * Returns structured authentic exam paper content for any Algerian BAC exam item
 */
export function getExamFullDetails(exam: BacExamItem): ExamFullDetails {
  const stream = ALGERIAN_BAC_STREAMS[exam.streamId];
  const subject = ALL_SUBJECTS[exam.subjectId];

  const streamName = stream?.name_ar || exam.streamId;
  const subjectName = subject?.name_ar || exam.subjectId;
  const hours = Math.floor((exam.durationMinutes || 210) / 60);
  const minutes = (exam.durationMinutes || 210) % 60;
  const durationLabel = `${hours.toString().padStart(2, "0")} سا ${minutes > 0 ? `و ${minutes} د` : ""}`;
  const coefficient = exam.coefficient || 2;

  // Resolve topics and exercises dynamically based on subject & stream
  const { topic1, topic2 } = buildTopicContent(exam, streamName, subjectName);

  return {
    exam,
    streamName,
    subjectName,
    durationLabel,
    coefficient,
    topic1,
    topic2,
    ministryGuidelines: [
      "على المترشح قراءة الموضوعين بعناية واختيار موضوع واحد فقط لمعالجته كلياً.",
      "تمنح مدة 30 دقيقة إضافية في بداية الاختبار لتسهيل اختيار الموضوع.",
      "تعتبر الدقة والمنهجية العلمية واللغوية ووضوح الخط عناصر حاسمة في تقييم الإجابة.",
      "يسمح باستعمال الآلة الحاسبة العلمية غير المبرمجة فقط في المواد العلمية والتقنية.",
    ],
  };
}

